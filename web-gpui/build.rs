//! Generates the embedded icon table for the browser build (see
//! `src/icon_assets.rs`). GPUI resolves `IconName`s through an `AssetSource`
//! by path (e.g. `icons/play.svg`), and the wasm payload has no filesystem to
//! load them from, so every SVG in `assets/icons/` is included with
//! `include_bytes!` and matched by its GPUI asset path.

use std::{env, fs, path::PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=assets/icons");

    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let icons_dir = manifest_dir.join("assets/icons");

    let mut icons: Vec<String> = fs::read_dir(&icons_dir)
        .map(|entries| {
            entries
                .filter_map(|entry| entry.ok())
                .filter_map(|entry| entry.file_name().into_string().ok())
                .filter(|name| name.ends_with(".svg"))
                .collect()
        })
        .unwrap_or_default();
    icons.sort();

    let mut generated =
        String::from("// Generated by web-gpui/build.rs from assets/icons; do not edit.\n");
    generated.push_str(
        "pub(crate) fn load_embedded_icon(path: &str) -> Option<std::borrow::Cow<'static, [u8]>> {\n",
    );
    if icons.is_empty() {
        generated.push_str("    let _ = path;\n    None\n");
    } else {
        generated.push_str("    match path {\n");
        for name in &icons {
            generated.push_str(&format!(
                r#"        "icons/{name}" => Some(std::borrow::Cow::Borrowed(include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/assets/icons/{name}")).as_slice())),
"#
            ));
        }
        generated.push_str("        _ => None,\n    }\n");
    }
    generated.push_str("}\n");

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("icons.rs"), generated).expect("write generated icons.rs");
}
